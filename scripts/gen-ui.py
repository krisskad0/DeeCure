"""Generate UI code from the UI spec, so the app always matches the docs.

  docs/03-ui-design/01-foundations/icons.md  ->  app/src/spec/icons.ts
  docs/03-ui-design/02-shell/sidebar.md      ->  app/src/spec/pages.ts

Usage: scripts/gen-ui.py           write the files
       scripts/gen-ui.py --check   fail if the files are out of date (CI)
"""

import json
import re
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
DESIGN = REPO / "docs" / "03-ui-design"
OUT = REPO / "app" / "src" / "spec"
HEADER = "// Generated by scripts/gen-ui.py from {source}. Do not edit by hand.\n\n"


def table_rows(path: Path, first_header: str):
    """The rows of the Markdown table whose header starts with `first_header`."""
    rows, inside = [], False
    for line in path.read_text(encoding="utf-8").splitlines():
        if line.startswith(f"| {first_header} |"):
            inside = True
            continue
        if inside and line.startswith("| ---"):
            continue
        if inside and line.startswith("|"):
            rows.append([cell.strip() for cell in line.strip().strip("|").split("|")])
        elif inside:
            break
    if not rows:
        sys.exit(f"{path}: no table starting with '| {first_header} |'")
    return rows


def code(cell: str) -> str:
    match = re.fullmatch(r"`([^`]+)`", cell)
    if not match:
        sys.exit(f"expected a `code` cell, got: {cell}")
    return match.group(1)


def icons_ts() -> str:
    source = DESIGN / "01-foundations" / "icons.md"
    icons = {code(name): code(path) for name, path in table_rows(source, "Name")}
    lines = [f"  {name}: {json.dumps(path)}," for name, path in icons.items()]
    return (
        HEADER.format(source=source.relative_to(REPO))
        + "/** Every icon: a 24×24 viewBox path, drawn with a 1.8 stroke. */\n"
        + "export const ICONS = {\n" + "\n".join(lines) + "\n} as const;\n\n"
        + "export type IconName = keyof typeof ICONS;\n"
    )


def pages_ts() -> str:
    source = DESIGN / "02-shell" / "sidebar.md"
    spec_files = {p.stem.split("-", 1)[1]: p.name for p in (DESIGN / "05-pages").glob("[0-9][0-9]-*.md")}
    pages = []
    for group, label, page_id, icon, _status, _mark, tabs in table_rows(source, "Group"):
        page_id = code(page_id)
        tab_list = []
        for part in tabs.split(" · "):
            match = re.fullmatch(r"`([^`]+)`: (.+)", part.strip())
            if not match:
                sys.exit(f"{source}: cannot read sub-page '{part}'")
            # Counts such as "(count 9, red)" are prototype sample data, not labels.
            tab_label = re.sub(r"\s*\(count [^)]*\)", "", match.group(2)).strip()
            tab_list.append({"id": match.group(1), "label": tab_label})
        if page_id not in spec_files:
            sys.exit(f"no page spec file for '{page_id}' in {DESIGN / '05-pages'}")
        pages.append({
            "id": page_id,
            "label": label,
            "group": group,
            "icon": code(icon),
            "spec": f"docs/03-ui-design/05-pages/{spec_files[page_id]}",
            "tabs": tab_list,
        })
    body = ",\n".join("  " + json.dumps(page, ensure_ascii=False) for page in pages)
    return (
        HEADER.format(source=source.relative_to(REPO))
        + 'import type { IconName } from "./icons";\n\n'
        + "export interface PageSpec {\n"
        + "  id: string;\n  label: string;\n  group: string;\n  icon: IconName;\n"
        + "  /** The page's spec file, relative to the repo root. */\n  spec: string;\n"
        + "  tabs: readonly { id: string; label: string }[];\n}\n\n"
        + "/** All pages, in sidebar order. */\n"
        + "export const PAGES: readonly PageSpec[] = [\n" + body + ",\n];\n"
    )


def main():
    check = "--check" in sys.argv[1:]
    outputs = {OUT / "icons.ts": icons_ts(), OUT / "pages.ts": pages_ts()}
    stale = []
    for path, text in outputs.items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == text:
            continue
        if check:
            stale.append(str(path.relative_to(REPO)))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_text(text, encoding="utf-8")
            print(f"wrote {path.relative_to(REPO)}")
    if stale:
        sys.exit("out of date (run scripts/gen-ui.py): " + ", ".join(stale))


if __name__ == "__main__":
    main()
